from m2 import run, INFL
def row(name,**k):
    r=run(**k); fs=r['first'] if r['first'] else 'none to 80'
    print(f"| {name} | {r['cov']*100:.0f}% | {fs} | {r['yrs']} of {80-k.get('ret',50)+1} | {r['sf']/1e6:.2f}m | {r['real']/1e3:,.0f}k | {r['cap']/1e3:,.0f}k |")
print("name|cov|first|yrs|nomSF|realSF|cap")
row("Baseline")
for a in (55,60,65): row(f"Retire {a}",ret=a)
row("+850/mo",extra_m=850)
row("+425/mo",extra_m=425)
row("SP full",sp_wk=299.30)
row("SP 70%",sp_wk=299.30,sp_pct=0.7)
for s in (35000,30000): row(f"Spend {s}",spend=s)
row("AE only",pension='ae')
row("PRSA redirect",pension='prsa')
row("PRSA+AE? (prsa)",pension='prsa')
row("Retire60+SP full",ret=60,sp_wk=299.30)
row("Ret 60 + SP70 + PRSA",ret=60,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 60 + SP70 + PRSA + 850",ret=60,sp_wk=299.30,sp_pct=.7,pension='prsa',extra_m=850)
row("Ret 65 + SP70 +PRSA",ret=65,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 55 + SP70 + PRSA",ret=55,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 50 +SP70+PRSA",ret=50,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 50 + SP70 + PRSA + 850",ret=50,sp_wk=299.30,sp_pct=.7,pension='prsa',extra_m=850)
row("Ret 55, spend 35, SP70, PRSA",ret=55,spend=35000,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 60, spend 35, SP70, PRSA",ret=60,spend=35000,sp_wk=299.30,sp_pct=.7,pension='prsa')
row("Ret 60, spend 40, SP70, PRSA, +425",ret=60,sp_wk=299.30,sp_pct=.7,pension='prsa',extra_m=425)
print("--- inflation sens (baseline, pay 3%)")
for i in (0.02,0.025,0.03,0.039):
    r=run(infl=i); print(i,round(r['cov']*100,1),r['first'],round(40000*(1+i)**23))
